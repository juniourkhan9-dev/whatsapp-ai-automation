const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');

function generateAppointmentPDF(data, outputPath) {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({ margin: 50 });
        const stream = fs.createWriteStream(outputPath);

        doc.pipe(stream);

        // Header Background
        doc.rect(0, 0, doc.page.width, 100).fill('#075e54');

        // Header Text
        doc.fillColor('#ffffff')
           .fontSize(22)
           .font('Helvetica-Bold')
           .text('APPOINTMENT CONFIRMATION', 50, 35, { align: 'center' });

        doc.fontSize(12)
           .font('Helvetica')
           .text('AI Automated Booking Slip', 50, 65, { align: 'center' });

        doc.moveDown(4);

        // Booking Reference ID
        const bookingId = 'BK-' + Math.floor(100000 + Math.random() * 900000);
        doc.fillColor('#333333')
           .fontSize(12)
           .font('Helvetica-Bold')
           .text(`Booking ID: ${bookingId}`, 50, 125);

        doc.font('Helvetica')
           .text(`Issued On: ${new Date().toLocaleString()}`, 50, 142);

        doc.moveTo(50, 165).lineTo(doc.page.width - 50, 165).strokeColor('#00a884').lineWidth(2).stroke();

        // Customer Details Box
        doc.rect(50, 180, doc.page.width - 100, 150).fillAndStroke('#f0f9f6', '#00a884');

        doc.fillColor('#075e54')
           .fontSize(14)
           .font('Helvetica-Bold')
           .text('Customer & Appointment Details', 70, 195);

        doc.fillColor('#222222')
           .fontSize(11)
           .font('Helvetica');

        const leftCol = 70;
        const rightCol = 220;
        let y = 225;

        const details = [
            { label: 'Client Name:', value: data.name || 'N/A' },
            { label: 'Phone Number:', value: data.phone || 'N/A' },
            { label: 'Date & Time:', value: `${data.date || 'TBD'} at ${data.time || 'TBD'}` },
            { label: 'Location / Address:', value: data.address || 'N/A' },
            { label: 'Status:', value: 'CONFIRMED (Slot Booked in Calendar)' }
        ];

        details.forEach(item => {
            doc.font('Helvetica-Bold').text(item.label, leftCol, y);
            doc.font('Helvetica').text(item.value, rightCol, y);
            y += 20;
        });

        // Client Requirement Section
        y = 350;
        doc.fillColor('#075e54')
           .fontSize(14)
           .font('Helvetica-Bold')
           .text('Client Requirements / Notes', 50, y);

        y += 25;
        doc.rect(50, y, doc.page.width - 100, 80).fillAndStroke('#fafafa', '#e0e0e0');

        doc.fillColor('#444444')
           .fontSize(11)
           .font('Helvetica')
           .text(data.requirement || 'Customer requested service inquiry and demo setup.', 65, y + 15, {
               width: doc.page.width - 130,
               align: 'left'
           });

        // Footer / Instructions
        y = 480;
        doc.fillColor('#666666')
           .fontSize(10)
           .text('Important Instructions:', 50, y);
        y += 16;
        doc.text('• Please be available at the scheduled time or keep your phone nearby.', 50, y);
        y += 14;
        doc.text('• To reschedule or cancel, reply to the WhatsApp chat.', 50, y);
        y += 14;
        doc.text('• This is an automated slip generated by WhatsApp AI Assistant.', 50, y);

        // Bottom green bar
        doc.rect(0, doc.page.height - 30, doc.page.width, 30).fill('#075e54');
        doc.fillColor('#ffffff')
           .fontSize(9)
           .text('Powered by AI Voice & WhatsApp Automation Engine', 0, doc.page.height - 20, { align: 'center' });

        doc.end();

        stream.on('finish', () => resolve(bookingId));
        stream.on('error', reject);
    });
}

module.exports = { generateAppointmentPDF };
